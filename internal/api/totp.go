// Two-factor login (#192, RFC 6238): 6 digits, 30 s step, SHA-1 (what every authenticator app speaks), ±1 step
// of clock skew. The secret is sealed with the credential box when there is one. Ten single-use recovery codes
// are stored as hashes. `mtmon passwd --reset-2fa` switches it off from the shell.

const (
	totpStep    = 30
	totpDigits  = 6
	metaSecret2 = "totp_secret"  // "" = off; "enc:<base64>" sealed, "raw:<base32>" without box
	metaPending = "totp_pending" // secret generated by setup, not yet confirmed
	metaRecov   = "totp_recovery"
	metaLast    = "totp_last" // last accepted time step: a code works once
)

func init() {
	routeHooks = append(routeHooks, func(s *Server, m *http.ServeMux, a func(http.HandlerFunc) http.HandlerFunc) {
		m.HandleFunc("GET /api/totp", a(s.totpState))
		m.HandleFunc("POST /api/totp/setup", a(s.totpSetup))
		m.HandleFunc("POST /api/totp/enable", a(s.totpEnable))
		m.HandleFunc("POST /api/totp/disable", a(s.totpDisable))
	})
}

func totpAt(secret []byte, step int64) string {
	mac := hmac.New(sha1.New, secret)
	var b [8]byte
	binary.BigEndian.PutUint64(b[:], uint64(step))
	mac.Write(b[:])
	sum := mac.Sum(nil)
	off := sum[len(sum)-1] & 0x0f
	v := binary.BigEndian.Uint32(sum[off:off+4]) & 0x7fffffff
	return fmt.Sprintf("%0*d", totpDigits, v%1000000)
}

// totpMatch returns the time step the code belongs to (now ±1), or 0.
func totpMatch(secret []byte, code string, now time.Time) int64 {
	code = strings.ReplaceAll(strings.TrimSpace(code), " ", "")
	if len(code) != totpDigits {
		return 0
	}
	cur := now.Unix() / totpStep
	for _, d := range []int64{0, -1, 1} {
		if subtle.ConstantTimeCompare([]byte(totpAt(secret, cur+d)), []byte(code)) == 1 {
			return cur + d
		}
	}
	return 0
}

var b32 = base32.StdEncoding.WithPadding(base32.NoPadding)

func (s *Server) totpSecret(key string) []byte {
	v := s.St.GetMeta(key)
	switch {
	case strings.HasPrefix(v, "enc:") && s.Box != nil:
		raw, err := base64.StdEncoding.DecodeString(v[4:])
		if err != nil {
			return nil
		}
		plain, err := s.Box.Open(raw)
		if err != nil {
			return nil
		}
		b, _ := b32.DecodeString(plain)
		return b
	case strings.HasPrefix(v, "raw:"):
		b, _ := b32.DecodeString(v[4:])
		return b
	}
	return nil
}

func (s *Server) setTOTPSecret(key string, secret []byte) {
	enc := b32.EncodeToString(secret)
	if s.Box != nil {
		s.St.SetMeta(key, "enc:"+base64.StdEncoding.EncodeToString(s.Box.Seal(enc)))
		return
	}
	s.St.SetMeta(key, "raw:"+enc)
}

func (s *Server) totpEnabled() bool { return s.St.GetMeta(metaSecret2) != "" }

var totpMu sync.Mutex

// totpCheck accepts an authenticator code (once per time step) or an unused recovery code.
func (s *Server) totpCheck(code string, now time.Time) bool {
	totpMu.Lock()
	defer totpMu.Unlock()
	code = strings.TrimSpace(code)
	if secret := s.totpSecret(metaSecret2); len(secret) > 0 {
		if step := totpMatch(secret, code, now); step != 0 {
			var last int64
			fmt.Sscan(s.St.GetMeta(metaLast), &last)
			if step <= last {
				return false // replay of a code that was already used
			}
			s.St.SetMeta(metaLast, fmt.Sprint(step))
			return true
		}
	}
	norm := strings.ToLower(strings.ReplaceAll(code, "-", ""))
	if len(norm) != 10 {
		return false
	}
	var hashes []string
	json.Unmarshal([]byte(s.St.GetMeta(metaRecov)), &hashes)
	h := hashToken(norm)
	for i, x := range hashes {
		if subtle.ConstantTimeCompare([]byte(x), []byte(h)) == 1 {
			hashes = append(hashes[:i], hashes[i+1:]...)
			b, _ := json.Marshal(hashes)
			s.St.SetMeta(metaRecov, string(b))
			return true
		}
	}
	return false
}

// totpGate protects actions that use router admin logins: with 2FA on they need a fresh code in X-TOTP-Code.
func (s *Server) totpGate(w http.ResponseWriter, r *http.Request) bool {
	if !s.totpEnabled() || !routerLoginRoute[r.Pattern] {
		return true
	}
	if !s.totpCheck(r.Header.Get("X-TOTP-Code"), time.Now()) {
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusForbidden)
		json.NewEncoder(w).Encode(map[string]any{"error": "two-factor code required", "totp_required": true})
		return false
	}
	return true
}

// routes that take a router admin login in the request body
var routerLoginRoute = map[string]bool{
	"POST /api/devices/probe":           true,
	"POST /api/devices/plan":            true,
	"POST /api/devices/provision":       true,
	"POST /api/devices/{name}/offboard": true,
	"POST /api/devices/{name}/features": true,
	"PUT /api/devices/{name}":           true,
}

func (s *Server) totpState(w http.ResponseWriter, r *http.Request) {
	var n int
	var hashes []string
	if json.Unmarshal([]byte(s.St.GetMeta(metaRecov)), &hashes) == nil {
		n = len(hashes)
	}
	jsonOut(w, map[string]any{"enabled": s.totpEnabled(), "recovery_left": n})
}

// totpSetup: POST /api/totp/setup → {secret, uri}. Nothing is active until /enable confirms a code.
func (s *Server) totpSetup(w http.ResponseWriter, r *http.Request) {
	if s.totpEnabled() {
		jerr(w, http.StatusConflict, "two-factor login is already on")
		return
	}
	secret := make([]byte, 20)
	rand.Read(secret)
	s.setTOTPSecret(metaPending, secret)
	enc := b32.EncodeToString(secret)
	label := url.PathEscape("mtmon:" + s.Cfg.AdminUser)
	jsonOut(w, map[string]string{"secret": enc, "uri": "otpauth://totp/" + label + "?secret=" + enc + "&issuer=mtmon&algorithm=SHA1&digits=6&period=30"})
}

// totpEnable: POST /api/totp/enable {code} → {recovery:[10 codes]}, shown once.
func (s *Server) totpEnable(w http.ResponseWriter, r *http.Request) {
	var in struct{ Code string }
	if !readJSON(w, r, &in) {
		return
	}
	pending := s.totpSecret(metaPending)
	step := int64(0)
	if len(pending) > 0 {
		step = totpMatch(pending, in.Code, time.Now())
	}
	if step == 0 {
		jerr(w, http.StatusBadRequest, "wrong code – check the time on your phone and try again")
		return
	}
	codes := make([]string, 10)
	hashes := make([]string, 10)
	for i := range codes {
		raw := make([]byte, 6)
		rand.Read(raw)
		plain := strings.ToLower(b32.EncodeToString(raw))[:10]
		codes[i] = plain[:5] + "-" + plain[5:]
		hashes[i] = hashToken(plain)
	}
	hb, _ := json.Marshal(hashes)
	s.St.SetMeta(metaRecov, string(hb))
	s.St.SetMeta(metaLast, fmt.Sprint(step))
	s.St.SetMeta(metaSecret2, s.St.GetMeta(metaPending))
	s.St.SetMeta(metaPending, "")
	s.audit(s.Cfg.AdminUser, sourceIP(r), "security.2fa-on", "")
	jsonOut(w, map[string]any{"recovery": codes})
}

// totpDisable: POST /api/totp/disable {password, code}
func (s *Server) totpDisable(w http.ResponseWriter, r *http.Request) {
	var in struct{ Password, Code string }
	if !readJSON(w, r, &in) {
		return
	}
	if !CheckPassword(in.Password, s.Cfg.AdminHash) || !s.totpCheck(in.Code, time.Now()) {
		jerr(w, http.StatusForbidden, "password or code wrong")
		return
	}
	s.resetTOTP()
	s.audit(s.Cfg.AdminUser, sourceIP(r), "security.2fa-off", "")
	jsonOut(w, map[string]bool{"enabled": false})
}

func (s *Server) resetTOTP() {
	for _, k := range []string{metaSecret2, metaPending, metaRecov, metaLast} {
		s.St.SetMeta(k, "")
	}
}
